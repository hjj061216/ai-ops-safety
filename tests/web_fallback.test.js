// 使用页面的真实脚本，验证候选失效、离线提示、表单和反馈分离。
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
async function main() {
  const html = fs.readFileSync(path.join(__dirname, '..', 'web', 'index.html'), 'utf8');
  const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
  const elements = {}, handlers = {};
  const getElement = id => elements[id] ||= {
    value: '', disabled: false, hidden: false, open: false, dataset: {}, attributes: {}, textContent: '', focus() {}, setAttribute(name, value) { this.attributes[name] = value; },
    addEventListener(event, handler) { handlers[id+':'+event] = handler; }
  };
  let interpretation, executeCalls = 0;
  const sent = [];
  const context = vm.createContext({
    window: {crypto:require('node:crypto').webcrypto}, setInterval: () => 0,
    document: {getElementById: getElement, querySelectorAll: () => Object.values(elements)},
    fetch: async (url, options = {}) => {
      const body = options.body ? JSON.parse(options.body) : {};
      if (options.method === 'POST') sent.push({url, body});
      if (url === '/api/execute') executeCalls++;
      let data;
      if (url === '/api/interpret') data = await interpretation();
      else if (url === '/api/check') data = {decision: body.candidate_id === 'manual' ? 'require_human' : 'allow', effective_risk: body.candidate_id === 'manual' ? 'medium' : 'low'};
      else if (url === '/api/candidates/manual') data = {actionable: true, candidate_id: 'manual', tool: body.tool, arguments: body.arguments, effective_risk: 'medium', expires_at: Date.now()/1000+900};
      else if (url === '/api/execute') data = {executed: true, operation: {operation_id: 'test-operation', result: {}, rollback_available: false}};
      else if (url === '/api/approvals/request') data = {request_id: 'manual-approval'};
      else if (url === '/api/approvals/approve') data = {approval_token: 'test-private-token'};
      else data = {approvals: [], operations: [], audit: {count: 0}};
      return {ok: true, status: 200, json: async () => ({ok: true, data})};
    }
  });
  vm.runInContext(fs.readFileSync(path.join(__dirname,'..','web','workbench.js'),'utf8'),context);
  vm.runInContext(script, context);
  await new Promise(resolve => setImmediate(resolve));
  const ui = context.window.opsConsole;
  assert.equal(ui.getState().mode, 'natural');
  assert.equal(getElement('naturalInputPanel').hidden, false);
  assert.equal(getElement('manualInputPanel').hidden, true);
  assert.equal(getElement('naturalModeButton').attributes['aria-pressed'], 'true');
  assert.equal(getElement('debugModeButton').attributes['aria-pressed'], 'false');
  assert.equal(getElement('manualCandidateButton').disabled, true);
  assert.equal(getElement('advancedMode').open, false);
  getElement('role').value = 'viewer';
  getElement('naturalRequest').value = '查看磁盘使用情况';
  let finish;
  interpretation = () => new Promise(resolve => {finish = resolve;});
  const pending = ui.interpretRequest();
  assert.equal(getElement('debugModeButton').disabled, true);
  assert.equal(ui.setMode('manual'), false);
  assert.equal(ui.getState().mode, 'natural');
  assert.equal(ui.getState().candidate, null);
  assert.equal(getElement('requestId').value, '');
  assert.equal(getElement('executeButton').disabled, true);
  await ui.executeCall();
  assert.equal(executeCalls, 0);
  finish({actionable: true, candidate_id: 'offline', tool: 'check_disk', arguments: {}, effective_risk: 'low',
    candidate_source: 'offline_rules', expires_at: Date.now()/1000+900,
    message: 'AI 服务暂不可用，已通过离线规则识别此只读查询。', recovery: ['启动 Ollama 后重试。']});
  await pending;
  assert.equal(ui.getState().candidate.tool, 'check_disk');
  assert.equal(ui.getState().checked, true);
  assert.equal(getElement('executeButton').disabled, false);
  assert.equal(sent.filter(request => request.url === '/api/check').length, 1);
  assert.match(getElement('analysisMessage').textContent, /离线规则/);
  assert.match(getElement('candidateSource').textContent, /离线只读规则/);
  await ui.checkCall();
  assert.equal(getElement('executeButton').disabled, false);
  assert.equal(getElement('approvalPanel').hidden, true);
  const candidateBeforeDetails = ui.getState().candidate.id;
  getElement('advancedMode').open = true; handlers['advancedMode:toggle']();
  assert.equal(ui.getState().mode, 'natural');
  assert.equal(ui.getState().candidate.id, candidateBeforeDetails);
  getElement('manualTool').value = 'read_log'; handlers['manualTool:change']();
  assert.equal(ui.getState().candidate.id, candidateBeforeDetails);
  getElement('advancedMode').open = false; handlers['advancedMode:toggle']();
  assert.equal(ui.getState().candidate.id, candidateBeforeDetails);
  assert.match(getElement('feedbackMessage').textContent, /检查通过，但尚未执行/);
  assert.equal(executeCalls, 0);
  const body = ui.payload();
  assert.equal(body.candidate_id, 'offline');
  assert.ok(!Object.hasOwn(body, 'llm_risk'));
  assert.ok(!Object.hasOwn(body, 'risk'));
  await ui.executeCall();
  assert.equal(executeCalls, 1);
  assert.equal(ui.getState().candidate, null);
  assert.match(getElement('executionStatus').textContent, /已完成本地工具执行/);
  interpretation = async () => ({actionable: false, message: 'AI 服务不可用，请使用高级手动表单。'});
  await ui.interpretRequest();
  assert.equal(ui.getState().candidate, null);
  assert.equal(getElement('executeButton').disabled, true);
  assert.match(getElement('analysisMessage').textContent, /手动/);
  assert.match(getElement('executionStatus').textContent, /上次结果/);
  ui.setMode('manual');
  assert.equal(getElement('naturalInputPanel').hidden, true);
  assert.equal(getElement('manualInputPanel').hidden, false);
  assert.equal(getElement('naturalModeButton').attributes['aria-pressed'], 'false');
  assert.equal(getElement('debugModeButton').attributes['aria-pressed'], 'true');
  assert.equal(getElement('interpretButton').disabled, true);
  assert.equal(executeCalls, 1);
  getElement('manualTool').value = 'read_log';
  getElement('logPath').value = '/var/log/nginx/error.log';
  getElement('logLines').value = '2';
  assert.equal(JSON.stringify(ui.buildManualArguments()), JSON.stringify({path:'/var/log/nginx/error.log',lines:2}));
  await ui.generateManualCandidate();
  assert.equal(ui.getState().candidate.risk, 'medium');
  assert.equal(ui.getState().checked, true);
  assert.equal(ui.getState().checkDecision, 'require_human');
  await ui.checkCall();
  assert.equal(getElement('executeButton').disabled, true);
  assert.equal(getElement('requestApprovalButton').disabled, false);
  assert.equal(getElement('approvalPanel').hidden, false);
  getElement('requester').value = 'alice'; getElement('reason').value = 'test';
  getElement('approver').value = 'bob'; getElement('approverRole').value = 'admin';
  await ui.requestApproval(); await ui.approveRequest();
  assert.equal(ui.getState().hasApprovalToken, true);
  getElement('advancedMode').open = false; handlers['advancedMode:toggle']();
  getElement('advancedMode').open = true; handlers['advancedMode:toggle']();
  assert.equal(ui.getState().hasApprovalToken, true);
  await ui.checkCall();
  assert.equal(ui.getState().hasApprovalToken, true);
  assert.equal(getElement('feedbackDetails').textContent.includes('test-private-token'), false);
  ui.setMode('manual');
  assert.equal(ui.getState().hasApprovalToken, true);
  ui.setMode('natural');
  assert.equal(ui.getState().candidate, null);
  assert.equal(ui.getState().requestId, '');
  assert.equal(ui.getState().hasApprovalToken, false);
  assert.equal(getElement('approvalPanel').hidden, true);
  assert.equal(getElement('executeButton').disabled, true);
  assert.equal(getElement('naturalInputPanel').hidden, false);
  assert.equal(getElement('manualInputPanel').hidden, true);
  assert.match(getElement('feedbackMessage').textContent, /输入方式已切换/);
  ui.setMode('manual');
  assert.equal(executeCalls, 1);
  await ui.generateManualCandidate(); await ui.checkCall();
  await ui.requestApproval(); await ui.approveRequest();
  assert.equal(ui.getState().hasApprovalToken, true);
  getElement('naturalRequest').value = '隐藏的自然语言草稿'; handlers['naturalRequest:input']();
  assert.equal(ui.getState().hasApprovalToken, true);
  getElement('logLines').value = '3'; handlers['logLines:input']();
  assert.equal(ui.getState().candidate, null);
  assert.equal(ui.getState().hasApprovalToken, false);
  assert.equal(getElement('approvalPanel').hidden, true);
  assert.equal(getElement('checkButton').disabled, true);
  interpretation = async () => {throw new Error('连接中断');};
  await ui.interpretRequest();
  assert.equal(getElement('executeButton').disabled, true);
  assert.equal(ui.getState().candidate, null);
  assert.equal(getElement('interpretButton').disabled, false);
  assert.match(getElement('analysisMessage').textContent, /连接中断/);
  for (const request of sent) assert.ok(!Object.hasOwn(request.body, 'llm_risk'));
  console.log('Web mode buttons, fallback and server-bound candidate behavior passed.');
}
main().catch(error => {console.error(error); process.exitCode = 1;});
